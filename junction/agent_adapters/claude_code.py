"""
claude_code.py — Adapter for Claude Code (Anthropic).

Generates:
  CLAUDE.md          — top-level project context file (main session = orchestrator)
  .claude/agents/    — one subagent per graph node (six)
  .claude/commands/  — slash-command stubs for each major skill
"""

from __future__ import annotations

from typing import Optional

from junction.agent_adapters._base import AgentAdapter, agent_table
from junction.agent_specs import MCP_TOOL_TO_SERVER, AgentSpec
from junction.config_builder import PlatformConfig
from junction.models import claude_code_alias

# Graph tool names → Claude Code tools
_TOOL_MAP = {
    "read": ["Read", "Glob"],
    "search": ["Grep", "Glob"],
    "grep": ["Grep"],
    "get-errors": ["Bash"],
    "edit": ["Edit", "Write"],
    "terminal": ["Bash"],
    "ask-questions": [],
    "runSubagent": [],
}

_COLORS = {
    "orchestrator": "blue",
    "iac-validator": "green",
    "terraform-builder": "orange",
    "sre-observer": "cyan",
    "knowledge-curator": "purple",
    "migration-executor": "red",
}


class ClaudeCodeAdapter(AgentAdapter):
    name = "claude-code"

    def generate_files(self, platform: PlatformConfig, graph: Optional[dict] = None) -> dict[str, str]:
        agents = self.agents(platform, graph)
        specs = [spec for spec, _ in agents]
        files: dict[str, str] = {
            "CLAUDE.md": _claude_md(platform, specs),
        }
        for spec, body in agents:
            files[f".claude/agents/{spec.name}.md"] = _subagent_file(spec, body, specs)
        # Slash-command stubs
        commands = {
            "deploy": _cmd_deploy(platform),
            "promote": _cmd_promote(platform),
            "drift-check": _cmd_drift(platform),
            "sre-triage": _cmd_triage(platform),
            "health-check": _cmd_health(platform),
            "migrate": _cmd_migrate(platform),
        }
        for name, content in commands.items():
            files[f".claude/commands/{name}.md"] = content
        return files


def claude_code_tools(spec: AgentSpec, all_specs: list[AgentSpec]) -> list[str]:
    tools: list[str] = []
    if "runSubagent" in spec.tools:
        others = ", ".join(s.name for s in all_specs if s.name != spec.name)
        tools.append(f"Agent({others})")
    for tool in spec.tools:
        if tool.startswith("mcp:"):
            mapped = [f"mcp__{MCP_TOOL_TO_SERVER.get(tool, tool[4:])}"]
        else:
            mapped = _TOOL_MAP.get(tool, [])
        for m in mapped:
            if m not in tools:
                tools.append(m)
    return tools


def _subagent_file(spec: AgentSpec, body: str, all_specs: list[AgentSpec]) -> str:
    import json

    lines = [
        "---",
        f"name: {spec.name}",
        f"description: {json.dumps(spec.description, ensure_ascii=False)}",
        f"tools: {', '.join(claude_code_tools(spec, all_specs))}",
        f"model: {claude_code_alias(spec.model)}",
        f"color: {_COLORS.get(spec.name, 'blue')}",
    ]
    if spec.read_only:
        lines.append("disallowedTools: Edit, Write, NotebookEdit")
    lines.append("---")
    return "\n".join(lines) + "\n\n" + body


# ─── File generators ──────────────────────────────────────────────────────────


def _claude_md(p: PlatformConfig, specs: list[AgentSpec]) -> str:
    env_rows = "\n".join(
        f"| {e.name} | `{e.branch}` | `{e.account_id}` | `{e.prefix}` | `{e.risk_tier}` |"
        for e in p.environments
    )
    env_chain = " → ".join(e.name for e in p.environments)
    return f"""# {p.name} — Claude Code Context

> Generated by [junction](https://github.com/egen/junction)

This repository is managed by **Junction**.
Read this file before performing any infrastructure operation.

## Platform

| Attribute | Value |
|-----------|-------|
| IaC Tool | `{p.iac_tool}` |
| Cloud | `{p.cloud}` |
| Compute | `{p.compute_type}` |
| CI/CD | `{p.cicd_type}` |
| Application | `{p.application_name}` |

## Environment Chain

**Promotion order**: `{env_chain}` — never skip environments.

| Env | Branch | Account | Prefix | Risk Tier |
|-----|--------|---------|--------|-----------|
{env_rows}

## Agent Graph

This repo runs a six-agent graph (`.github/config/agent-graph.yml`). **The main
session acts as the Orchestrator**: follow `.claude/agents/orchestrator.md`, and
delegate each step to exactly one specialist subagent.

{agent_table(specs, ".claude/agents/{name}.md")}

- Every change from `terraform-builder` goes to `iac-validator` and must pass (≤3 fix cycles)
- `sre-observer` is read-only; resolved incidents go to `knowledge-curator`
- `migration-executor` is HIGH risk: no automatic retries, and it pauses for a human on failure

## Boot Protocol

**Before any action:**
1. `git branch --show-current` → confirm branch
2. Match branch to environment + risk tier (table above)
3. `HIGH` risk → require explicit confirmation for every change
4. Load `.github/config/platform.yml` and `.github/knowledge/service-registry.md`

## Key Rules

- **Never** copy env-specific values (account IDs, endpoints, secrets) between branches
- **Always** use MCP tools for logs, metrics, and issue tracker — never direct API calls
- **Always** scan for env-leak patterns before pushing
- **Always** include ticket ID in commit messages: `type(PROJ-123): description`
- **Read-only SRE** operations: use `.github/skills/_triage/` skills only

## Skills

Skills are in `.github/skills/`. Each has a SKILL.md with full instructions.

| Skill | Trigger |
|-------|---------|
| `env-promotion` | Promoting changes across environments |
| `self-healing-deploy` | Deploying a service with auto-remediation |
| `drift-detection` | Comparing env configs |
| `post-push-monitor` | Monitoring CI/CD after a push |
| `iac-triage` | Diagnosing plan/apply failures |
| `sre-log-fetching` | Fetching and analysing logs |
| `knowledge-curation` | Updating runbooks, registry and cross-links |
| `v1-v2-migration` | Phased, gated V1 → V2 migration |

## MCP Servers

| Server | Backend |
|--------|---------|
| cloud-logs | `{p.mcp.cloud_logs_backend}` |
| issue-tracker | `{p.mcp.issue_tracker_backend}` |
| observability | `{p.mcp.observability_backend}` |
| log-aggregator | `{p.mcp.log_aggregator_backend}` |

## Guardrails

See `.github/instructions/` for coding standards and production guardrails.
"""


def _cmd_deploy(p: PlatformConfig) -> str:
    env_opts = " | ".join(e.name for e in p.environments)
    return f"""# /deploy — Self-Healing Deploy

Deploy a service to an environment using the self-healing lifecycle.

## Usage

```
/deploy SERVICE_KEY=<key> NEW_TAG=<tag> ENV=<env>
```

**ENV options**: {env_opts}

## What happens

Follows `.github/skills/_core/self-healing-deploy/SKILL.md`:
1. Boot Protocol → confirm branch + risk tier
2. Update `tfvars/{{env}}.tfvars` with new tag
3. Commit + push
4. Monitor CI/CD (post-push-monitor)
5. Health gate → auto-remediate or escalate
6. Record learnings

## Risk gates

- `HIGH` risk env → requires explicit confirmation before step 2
- `MEDIUM` → requires promotion approval
"""


def _cmd_promote(p: PlatformConfig) -> str:
    if len(p.environments) >= 2:
        example_src = p.environments[0].name
        example_dst = p.environments[1].name
    else:
        example_src, example_dst = "dev", "staging"
    return f"""# /promote — Environment Promotion

Promote IaC changes from one environment to another.

## Usage

```
/promote from=<source_env> to=<target_env> [ticket=PROJ-123]
```

**Example**: `/promote from={example_src} to={example_dst} ticket=PROJ-456`

## What happens

Follows `.github/skills/_core/env-promotion/SKILL.md`:
1. Boot Protocol
2. Read source + target tfvars
3. Classify differences (env-unique vs promotable)
4. Merge — keep env-unique target values, promote everything else
5. Env-leak scan
6. Generate plan + changelog
7. Push (with approval for MEDIUM/HIGH risk)
"""


def _cmd_drift(p: PlatformConfig) -> str:
    if len(p.environments) >= 2:
        example = f"{p.environments[0].name} vs {p.environments[1].name}"
    else:
        example = "dev vs staging"
    return f"""# /drift-check — Drift Detection

Compare two environments for configuration drift.

## Usage

```
/drift-check source=<env> target=<env>
```

**Example**: `/drift-check source={example.split(' vs ')[0]} target={example.split(' vs ')[1]}`

## What happens

Follows `.github/skills/_core/drift-detection/SKILL.md`:
1. Read `tfvars/{{source}}.tfvars` and `tfvars/{{target}}.tfvars`
2. Diff service versions + config values
3. Classify: intentional | version lag | config drift | missing service
4. Report structured diff
"""


def _cmd_triage(p: PlatformConfig) -> str:
    return f"""# /sre-triage — SRE Triage

Investigate a service health issue using logs and APM.

## Usage

```
/sre-triage service=<service_key> env=<env> [window=30m]
```

## What happens

**READ-ONLY** — no modifications.

1. Load service registry → find log group + health contracts
2. Fetch logs from `{p.mcp.cloud_logs_backend}`
3. Query APM from `{p.mcp.observability_backend}`
4. Classify: HEALTHY | DEGRADED | UNHEALTHY
5. Report with root cause + recommended action
"""


def _cmd_health(p: PlatformConfig) -> str:
    env_opts = " | ".join(e.name for e in p.environments)
    return f"""# /health-check — Service Health Check

Quick health check for all services in an environment.

## Usage

```
/health-check env=<env>
```

**ENV options**: {env_opts}

## What happens

For each service in the registry:
1. Check container health (CPU, mem, restarts) via `{p.mcp.observability_backend}`
2. Check error rate (last 30 min)
3. Status: ✅ HEALTHY | ⚠️ DEGRADED | ❌ UNHEALTHY

Returns a summary table of all services.
"""


def _cmd_migrate(p: PlatformConfig) -> str:
    return """# /migrate — Gated V1 → V2 Migration

Advance a V1 → V2 migration by exactly one phase.

## Usage

```
/migrate phase=<next|status|rollback> [service=<service_key>] ticket=PROJ-123
```

## What happens

Delegates to the `migration-executor` subagent, which follows
`.github/skills/_core/v1-v2-migration/SKILL.md`:
1. Load migration state and confirm the current phase with the user
2. Prove parity (env vars, secrets, naming) against running V1
3. Execute the phase through `terraform-builder` → `iac-validator`
4. Health gate from `sre-observer`
5. On any failure: STOP, record state, and ask a human (no automatic retries)
"""
